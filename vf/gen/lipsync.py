"""Lip-sync a clip to a voice line with MuseTalk 1.5 (MIT; models in hero_film/tools/musetalk/models).
Face box from OpenCV YuNet (no MMLab/dwpose needed); the lower half of the face is regenerated by MuseTalk's
one-step latent inpainting and blended back through a soft jaw mask. Works best on the upscaled clip (bigger face).
Usage (gen venv): python -m vf.gen.lipsync clip.mp4 voice.wav offset_s out.mp4
  offset_s = when the line starts inside the clip; frames outside the line keep a closed mouth (silence)."""
import os, subprocess, sys, tempfile, time
_AI = os.environ.get('VF_AI_ROOT', r'D:\claude_work\hero_film')  # root of the AI venvs, tools and models (README: Configuration)
import cv2, numpy as np, torch, soundfile as sf

MT = os.path.join(_AI, 'tools', 'musetalk')
YUNET = os.path.join(os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))), 'cache',
                     'models', 'yunet', 'face_detection_yunet_2023mar.onnx')


def _boxes(frames):
    """Per-frame face box (x1, y1, x2, y2), smoothed over time (no jitter); None if no face."""
    H, W = frames[0].shape[:2]
    det = cv2.FaceDetectorYN.create(YUNET, '', (W, H), 0.6)
    raw = []
    for f in frames:
        _, faces = det.detect(f)
        if faces is None or not len(faces):
            raw.append(None)
            continue
        r = max(faces, key=lambda r: r[2] * r[3])
        x, y, w, h = r[:4]
        # YuNet landmarks: 0/1 eyes, 2 nose, 3/4 mouth corners -> real mouth centre and width (3/4 views put the
        # mouth far off the box centre; a box-centred patch gave doubled lips)
        mx, my = (r[10] + r[12]) / 2, (r[11] + r[13]) / 2
        mw = float(np.hypot(r[12] - r[10], r[13] - r[11]))
        # MuseTalk's training crop (preprocessing.get_landmark_and_bbox): nose at the vertical CENTRE, chin at the
        # bottom. A face box that starts at a hat brim makes it draw the mouth up by the nose (doubled lips).
        ny = r[9]
        chin = my + 1.25 * (my - ny)
        half = chin - ny
        raw.append(np.array([x, ny - half, x + w, chin, mx, my, mw], np.float32))
    ok = [b for b in raw if b is not None]
    if not ok:
        raise RuntimeError('no face found in the clip')
    last = ok[0]
    filled = []
    for b in raw:  # hold the last box through dropouts
        last = b if b is not None else last
        filled.append(last)
    a = np.stack(filled)
    k = 2  # light temporal smoothing: a lagging box pastes the mouth off the head = doubled lips
    pad = np.pad(a, ((k, k), (0, 0)), mode='edge')
    sm = np.stack([pad[i:i + 2 * k + 1].mean(0) for i in range(len(a))])
    return [(tuple(int(round(v)) for v in b[:4]), (float(b[4]), float(b[5]), float(b[6]))) for b in sm]


def run(clip, wav, offset, out, rate=1.0):
    """rate: the shot's playback speed; the clip plays slowed by it, so the voice is time-compressed by `rate` here
    (mouth shapes then land on the words after slow playback)."""
    sys.path.insert(0, MT)
    cwd = os.getcwd()
    os.chdir(MT)
    try:
        from transformers import WhisperModel
        from musetalk.utils.utils import load_all_model, datagen
        from musetalk.utils.audio_processor import AudioProcessor
        dev = torch.device('cuda')
        vae, unet, pe = load_all_model(device=dev)
        pe, vae.vae, unet.model = pe.half().to(dev), vae.vae.half().to(dev), unet.model.half().to(dev)
        ap = AudioProcessor(feature_extractor_path='models/whisper')
        whisper = WhisperModel.from_pretrained('models/whisper').to(dev, torch.float16).eval().requires_grad_(False)

        cap = cv2.VideoCapture(clip)
        fps = cap.get(cv2.CAP_PROP_FPS)
        frames = []
        while True:
            ok, f = cap.read()
            if not ok:
                break
            frames.append(f)
        n = len(frames)
        # voice placed at its offset inside a clip-long track
        y, sr = sf.read(wav, dtype='float32')
        if y.ndim > 1:
            y = y.mean(1)
        if abs(rate - 1) > 1e-3:  # time-compress (features only; pitch is irrelevant to the mouth model)
            m = max(1, int(round(len(y) * rate)))
            y = np.interp(np.linspace(0, len(y) - 1, m), np.arange(len(y)), y).astype(np.float32)
        if offset < 0:  # line starts before the clip window: drop the part that falls before frame 0
            y, offset = y[int(-offset * sr):], 0.0
        track = np.zeros(int(n / fps * sr) + sr // 2, np.float32)
        s0 = int(offset * sr)
        track[s0:s0 + len(y)] = y[:max(0, len(track) - s0)]
        tmp = tempfile.mktemp(suffix='.wav')
        sf.write(tmp, track, sr)
        feats, length = ap.get_audio_feature(tmp)
        # MuseTalk's chunker breaks above 50 fps: take features at its native 25 fps, map them onto our frames
        c25 = list(ap.get_whisper_chunk(feats, dev, torch.float16, whisper, length, fps=25,
                                        audio_padding_length_left=2, audio_padding_length_right=2))
        # interpolate between the 25 fps feature chunks (nearest-chunk held each mouth shape for several frames,
        # then snapped to the next one with a new lip colour = visible flicker at 90 fps / slowed shots, Q6 2026-11-03)
        def _chunk(i):
            u = i * 25 / fps
            k = min(len(c25) - 1, int(u))
            k2, w = min(len(c25) - 1, k + 1), u - int(u)
            return c25[k] if k2 == k or w < 1e-3 else c25[k] * (1 - w) + c25[k2] * w
        chunks = [_chunk(i) for i in range(n)]
        boxes = _boxes(frames)
        H, W = frames[0].shape[:2]
        crops, lat = [], []
        mouths = [b[1] for b in boxes]
        for f, ((x1, y1, x2, y2), _) in zip(frames, boxes):
            m = int(0.08 * (y2 - y1))  # v1.5 extra margin under the chin
            y1, y2 = max(0, y1), min(H, y2 + m)
            x1, x2 = max(0, x1), min(W, x2)
            crops.append((x1, y1, x2, y2))
            lat.append(vae.get_latents_for_unet(cv2.resize(f[y1:y2, x1:x2], (256, 256),
                                                             interpolation=cv2.INTER_LANCZOS4)))
        t = time.time()
        res = []
        ts = torch.tensor([0], device=dev)
        # 2026-11-03: batch 8 at 480x864 peaked at 7.7 GB + 1.2 GB spilled into shared memory. Batch 4 under a hard
        # allocator cap: an overflow raises OOM instead of paging (8 GB card).
        total = torch.cuda.get_device_properties(0).total_memory / 2**30
        torch.cuda.set_per_process_memory_fraction(min(1.0, float(os.environ.get('LS_VRAM_CAP', 6.5)) / total))
        torch.cuda.empty_cache()
        with torch.no_grad():
            for wb, lb in datagen(chunks[:n], lat, batch_size=int(os.environ.get('LS_BATCH', 4)), device=dev):
                feat = pe(wb.to(dev))
                pred = unet.model(lb.to(dev, torch.float16), ts, encoder_hidden_states=feat).sample
                res.extend(vae.decode_latents(pred))
        # blend: soft ellipse over mouth + jaw (lower ~55% of the face box)
        outf, masks = [], []
        for i, f in enumerate(frames):
            x1, y1, x2, y2 = crops[i]
            w, h = x2 - x1, y2 - y1
            face = cv2.resize(res[min(i, len(res) - 1)], (w, h), interpolation=cv2.INTER_CUBIC)
            mask = np.zeros((h, w), np.float32)
            # mouth + jaw, fully OPAQUE in the core (a see-through core shows the source lips = "double lips"),
            # feathered only in a thin rim and kept inside the face box (no seam under the chin)
            # centred on the DETECTED mouth (landmarks), sized from the mouth width
            mx, my, mw = mouths[i]
            cx, cy = int(round(mx - x1)), int(round(my - y1))
            if os.environ.get('LS_MASK') == 'lips2':
                # lips only, never the chin: MuseTalk redraws the whole lower face, and its own chin edge inside a
                # taller mask reads as a second "ghost" chin (2026-11-03). The patch is also matched in colour/tone
                # to the source skin around the mouth, so no lighter band shows.
                cv2.ellipse(mask, (cx, cy + int(0.04 * mw)), (int(0.8 * mw), int(0.4 * mw)), 0, 0, 360, 1.0, -1)
                k = max(3, int(0.3 * mw) // 2 * 2 + 1)
                ring = np.zeros((h, w), np.uint8)
                cv2.ellipse(ring, (cx, cy), (int(1.2 * mw), int(0.75 * mw)), 0, 0, 360, 1, -1)
                cv2.ellipse(ring, (cx, cy + int(0.04 * mw)), (int(0.8 * mw), int(0.4 * mw)), 0, 0, 360, 0, -1)
                rs = ring.astype(bool)
                if rs.sum() > 50:
                    src_lab = cv2.cvtColor(f[y1:y2, x1:x2], cv2.COLOR_BGR2LAB).astype(np.float32)
                    gen_lab = cv2.cvtColor(face, cv2.COLOR_BGR2LAB).astype(np.float32)
                    for ch in range(3):
                        ms, ss = src_lab[..., ch][rs].mean(), src_lab[..., ch][rs].std() + 1e-3
                        mg, sg = gen_lab[..., ch][rs].mean(), gen_lab[..., ch][rs].std() + 1e-3
                        gen_lab[..., ch] = (gen_lab[..., ch] - mg) * min(1.5, ss / sg) + ms
                    # lip colour: MuseTalk paints saturated pink lips; take the chroma (a, b) of the source lips
                    # only on the lip pixels themselves (red: a* well above the skin's); a shift of the whole patch
                    # turned the skin around the mouth green (rev 2)
                    core = np.zeros((h, w), np.uint8)
                    cv2.ellipse(core, (cx, cy), (int(0.9 * mw), int(0.5 * mw)), 0, 0, 360, 1, -1)
                    cs = core.astype(bool)
                    skin_a = src_lab[..., 1][rs].mean()
                    sl = cs & (src_lab[..., 1] > skin_a + 8)
                    gw = np.clip((gen_lab[..., 1] - skin_a - 4) / 12.0, 0, 1) * cs
                    gl = gw > 0.5
                    if sl.sum() > 20 and gl.sum() > 20:
                        for ch in (1, 2):
                            gen_lab[..., ch] += gw * (src_lab[..., ch][sl].mean() - gen_lab[..., ch][gl].mean())
                    face = cv2.cvtColor(gen_lab.clip(0, 255).astype(np.uint8), cv2.COLOR_LAB2BGR)
            elif os.environ.get('LS_MASK') == 'lips':  # bearded faces: replace the lips only, keep the source stubble
                cv2.ellipse(mask, (cx, cy + int(0.1 * mw)), (int(0.95 * mw), int(0.55 * mw)), 0, 0, 360, 1.0, -1)
                k = max(3, int(0.35 * mw) // 2 * 2 + 1)
            else:
                cv2.ellipse(mask, (cx, cy + int(0.25 * mw)), (int(1.3 * mw), int(1.0 * mw)), 0, 0, 360, 1.0, -1)
                k = max(3, int(0.5 * mw) // 2 * 2 + 1)
            mask = cv2.GaussianBlur(mask, (k, k), 0)
            mask = np.clip(mask * 1.6, 0, 1)[..., None]  # pushes the core to 1.0, the rim stays soft
            g = f.copy()
            roi = g[y1:y2, x1:x2].astype(np.float32)
            g[y1:y2, x1:x2] = (roi * (1 - mask) + face.astype(np.float32) * mask).clip(0, 255).astype(np.uint8)
            outf.append(g)
            masks.append((x1, y1, x2, y2, mask))
        # temporal smoothing inside the mouth patch only: each frame's patch is rendered on its own, so lip colour and
        # texture jitter frame to frame. A short [1,2,3,2,1] window over neighbouring frames (the face barely moves
        # between frames at >= 60 fps) removes the jitter; the frame outside the patch is untouched.
        # Lightness (the mouth SHAPE) uses a short window; colour (Lab a*, b*) a long one: closed lips have too few
        # lip pixels for the per-frame colour match, so the patch's own pink popped in at speech onsets (47.2 s).
        R = int(os.environ.get('LS_TSMOOTH', 4))
        RC = int(os.environ.get('LS_CSMOOTH', 4))
        if R > 0 and n > 2 * max(R, RC):
            lab = [cv2.cvtColor(o, cv2.COLOR_BGR2LAB) for o in outf]
            tri = lambda r: [(d, float(r + 1 - abs(d))) for d in range(-r, r + 1)]
            sm = []
            for i, (x1, y1, x2, y2, mask) in enumerate(masks):
                accL, accC, wl, wc = 0.0, 0.0, 0.0, 0.0
                for d, wd in tri(R):
                    j = min(n - 1, max(0, i + d))
                    accL = accL + wd * lab[j][y1:y2, x1:x2, :1].astype(np.float32); wl += wd
                for d, wd in tri(RC):
                    j = min(n - 1, max(0, i + d))
                    accC = accC + wd * lab[j][y1:y2, x1:x2, 1:].astype(np.float32); wc += wd
                cur = lab[i][y1:y2, x1:x2].astype(np.float32)
                new = np.concatenate([accL / wl, accC / wc], -1)
                mix = (cur * (1 - mask) + new * mask).clip(0, 255).astype(np.uint8)
                sm.append(cv2.cvtColor(mix, cv2.COLOR_LAB2BGR))
            for i, (x1, y1, x2, y2, _) in enumerate(masks):
                outf[i][y1:y2, x1:x2] = sm[i]
        dt = time.time() - t
        from .k6_batch import FFMPEG
        part = out + '.part.mp4'
        p = subprocess.Popen([FFMPEG, '-v', 'error', '-y', '-f', 'rawvideo', '-pix_fmt', 'bgr24', '-s', f'{W}x{H}', '-r',
                              f'{fps}', '-i', '-', '-c:v', 'h264_nvenc', '-tune', 'lossless', '-preset', 'medium', '-pix_fmt',
                              'yuv420p', part], stdin=subprocess.PIPE)
        p.stdin.write(np.stack(outf).tobytes())
        p.stdin.close()
        if p.wait():
            raise RuntimeError('ffmpeg failed')
        os.replace(part, out)
        os.remove(tmp)
        print(f'LIPSYNC {n} frames @ {fps:.1f} fps, model {dt:.1f}s -> {out}', flush=True)
    finally:
        os.chdir(cwd)


if __name__ == '__main__':
    a = sys.argv[1:]
    run(os.path.abspath(a[0]), os.path.abspath(a[1]), float(a[2]), os.path.abspath(a[3]),
        float(a[4]) if len(a) > 4 else 1.0)
