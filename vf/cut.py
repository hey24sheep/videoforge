"""`vf cut <episode.yaml>`: the full release cut of an episode = series intro + episode + series outro, checked,
joined, plus a phone copy under the size limit. Replaces the hand-written jobs/ep02_full_all.sh (2026-11-09).

series.yaml:
  intro: intro/episode.yaml      shared intro spec; a text layer containing {episode} gets the episode's label
  intro: titles/intro.mp4         intro/outro may be a finished video (e.g. a vf.mograph render), joined as it is
  outro: outro/episode.yaml      shared outro spec
  release: {name: MySeries}      file name prefix (default: the series folder name)
episode.yaml:
  episode: {no: 2, title: The Visitor}    -> label "EPISODE 2: THE VISITOR"  (or episode: {label: "..."})
  release: {wrap: false}                  -> no intro/outro (a teaser/trailer): build, check, phone copy only
  release: {intro_after: <shot id>}       -> cold open: the series intro plays after that shot, not first
  release: {intro: titles/intro_ep02.mp4} -> this episode's own intro (or outro), path from the series folder

Steps (each build is cache-backed: an unchanged intro/outro re-renders in ~20 s):
  1. writes <ep>/intro/episode.yaml (the series intro with the label filled in) and builds it
  2. builds the outro, then the episode (unless --skip-build)
  3. `vf check` on the episode (exit 1 = BLOCK: the cut is still made, but marked in the summary)
  4. joins intro + episode + outro at 60 fps -> <ep>/out/<Name>_epNN_<Title>_FULL.mp4 (h264 cq 19; NVENC or libx264)
  5. phone copy: HEVC (NVENC or libx265) at the bitrate that fits --phone-mb (default 28 MB, cap 4 Mb/s) -> ..._FULL_phone.mp4
Run it detached: python tools/jobwatch.py run --name <x> --env VF_GC=0 -- python -m vf cut <episode.yaml>
"""
import os, re, subprocess, sys

import yaml

from . import enc

PY = sys.executable


def _label(ep):
    e = ep.get('episode') or {}
    if e.get('label'):
        return str(e['label'])
    if e.get('no') and e.get('title'):
        return f"EPISODE {e['no']}: {str(e['title']).upper()}"
    return ''


def _fill(node, label):
    if isinstance(node, dict):
        return {k: _fill(v, label) for k, v in node.items()}
    if isinstance(node, list):
        return [_fill(v, label) for v in node]
    if isinstance(node, str) and '{episode}' in node:
        return node.replace('{episode}', label)
    return node


def _build(yaml_path, log):
    log(f'=== build {yaml_path}')
    r = subprocess.run([PY, '-m', 'vf', 'build', yaml_path, '--formats', 'short', '--allow-encode'])
    if r.returncode:
        raise SystemExit(f'build failed: {yaml_path}')
    out = os.path.join(os.path.dirname(yaml_path), 'out')
    c = [os.path.join(out, f) for f in os.listdir(out) if f.endswith('_short.mp4')]
    return max(c, key=os.path.getmtime)


def _dur(p):
    r = subprocess.run(['ffprobe', '-v', 'error', '-show_entries', 'format=duration', '-of', 'csv=p=0', p],
                       capture_output=True, text=True)
    return float(r.stdout.strip())


def cut(episode_yaml, skip_build=False, no_check=False, phone_mb=28.0, log=print):
    episode_yaml = os.path.abspath(episode_yaml)
    root = os.path.dirname(episode_yaml)
    sdir = os.path.dirname(root)
    se = yaml.safe_load(open(os.path.join(sdir, 'series.yaml'), encoding='utf-8')) or {}
    ep = yaml.safe_load(open(episode_yaml, encoding='utf-8')) or {}
    label = _label(ep)
    parts = []
    wrap = (ep.get('release') or {}).get('wrap', True)   # release: {wrap: false} = no series intro/outro (a trailer)
    if not wrap:
        se = dict(se, intro=None, outro=None)
    else:   # release: {intro: X, outro: Y} = this episode's own intro/outro (path from the series folder), e.g. a title card naming it
        se = dict(se, **{k: v for k, v in (ep.get('release') or {}).items() if k in ('intro', 'outro') and v})
    # a finished video (e.g. a vf.mograph title sequence) is joined as it is, no build
    vid = lambda k: se.get(k) and os.path.splitext(se[k])[1].lower() in ('.mp4', '.mov', '.mkv')
    pre_intro = os.path.join(sdir, se['intro']) if vid('intro') else None
    pre_outro = os.path.join(sdir, se['outro']) if vid('outro') else None
    se = dict(se, **({'intro': None} if pre_intro else {}), **({'outro': None} if pre_outro else {}))
    if se.get('intro'):
        intro = yaml.safe_load(open(os.path.join(sdir, se['intro']), encoding='utf-8'))
        if not label and '{episode}' in yaml.safe_dump(intro):
            raise SystemExit('the series intro shows {episode}: set episode: {no, title} in ' + episode_yaml)
        intro = _fill(intro, label)
        intro['series'] = '../../series.yaml'
        intro['title'] = (intro.get('title') or 'intro') + (f' ({label})' if label else '')
        idir = os.path.join(root, 'intro')
        os.makedirs(idir, exist_ok=True)
        ipath = os.path.join(idir, 'episode.yaml')
        with open(ipath, 'w', encoding='utf-8') as f:
            f.write('# GENERATED by `vf cut` from ' + se['intro'] + ' (edit that file, not this one)\n')
            yaml.safe_dump(intro, f, sort_keys=False, allow_unicode=True, width=200)
        parts.append(_build(ipath, log) if not skip_build else None)
    main = _build(episode_yaml, log) if not skip_build else None
    outro = _build(os.path.join(sdir, se['outro']), log) if se.get('outro') and not skip_build else None
    if skip_build:   # newest renders on disk
        def newest(d):
            o = os.path.join(d, 'out')
            c = [os.path.join(o, f) for f in os.listdir(o) if f.endswith('_short.mp4')]
            return max(c, key=os.path.getmtime)
        parts = [newest(os.path.join(root, 'intro'))] if se.get('intro') else []
        main = newest(root)
        outro = newest(os.path.join(sdir, os.path.dirname(se['outro']))) if se.get('outro') else None
    outro = pre_outro or outro
    parts = ([pre_intro] if pre_intro else []) + [p for p in parts if p] + [main] + ([outro] if outro else [])
    # cold open: release: {intro_after: <shot id>} plays the episode up to the end of that shot, then the series intro,
    # then the rest of the episode. A part is a path or (path, input options).
    after = (ep.get('release') or {}).get('intro_after')
    if after and se.get('intro') and len(parts) >= 2:
        import json
        tl = json.load(open(os.path.join(root, 'out', 'timeline.json'), encoding='utf-8'))
        hit = [s for s in tl if s['id'] == after]
        if not hit:
            raise SystemExit(f'release.intro_after: no shot {after!r} in the timeline')
        t = round(hit[0]['start'] + hit[0]['dur'], 3)
        intro_part = parts.pop(0)
        i = parts.index(main)
        parts[i:i + 1] = [(main, ['-t', str(t)]), intro_part, (main, ['-ss', str(t)])]
        log(f'=== cold open: intro after {after} at {t:.2f} s')
    ok = True
    if not no_check:
        log('=== check')
        ok = subprocess.run([PY, '-m', 'vf', 'check', episode_yaml, '--video', main]).returncode == 0
    name = (se.get('release') or {}).get('name') or os.path.basename(sdir).title().replace('_', '')
    e = ep.get('episode') or {}
    tag = f"ep{int(e['no']):02d}_" if e.get('no') else ''
    title = re.sub(r'[^A-Za-z0-9]+', '', str(e.get('title', '')).title()) or os.path.basename(root)
    full = os.path.join(root, 'out', f'{name}_{tag}{title}_FULL.mp4')
    n = len(parts)
    fc = ';'.join(f'[{i}:v]fps=60,format=yuv420p[v{i}]' for i in range(n)) + ';' + \
         ''.join(f'[v{i}][{i}:a]' for i in range(n)) + f'concat=n={n}:v=1:a=1[v][a]'
    log(f'=== join {n} part(s) -> {full}')
    inputs = sum([(list(p[1]) + ['-i', p[0]]) if isinstance(p, tuple) else ['-i', p] for p in parts], [])
    subprocess.run(['ffmpeg', '-v', 'error', '-y'] + inputs +
                   ['-filter_complex', fc, '-map', '[v]', '-map', '[a]'] + enc.join() + [
                    '-c:a', 'aac', '-b:a', '192k', '-movflags', '+faststart', full], check=True)
    dur = _dur(full)
    kbps = int(min(4000, max(500, (phone_mb * 8 * 1024 * enc.phone_overshoot()) / dur - 128)))
    phone = full[:-4] + '_phone.mp4'
    subprocess.run(['ffmpeg', '-v', 'error', '-y', '-i', full] + enc.phone(kbps) + ['-c:a', 'aac',
                    '-b:a', '128k', '-movflags', '+faststart', phone], check=True)
    mb = os.path.getsize(phone) / 2 ** 20
    log(f'[cut] {"PASS" if ok else "CHECK BLOCKED"}: {full} ({dur:.1f} s); phone {phone} ({mb:.1f} MB at {kbps} kb/s)')
    if mb > phone_mb + 1.5:
        log(f'[cut] WARN phone copy {mb:.1f} MB > {phone_mb} MB')
    return dict(full=full, phone=phone, ok=ok, mb=mb, dur=dur)
