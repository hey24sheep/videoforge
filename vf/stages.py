"""AI generation stage: turns each shot's `gen:` block into a finished, cached video layer.

shot:
  gen:
    image: path.png            # optional first frame you provide; else
    keyframe: "prompt"         # first frame generated by the image stage (vf.gen.image, Z-Image-Turbo)
    keyframe_seed: 3           # pick a different still without changing the clip seed
    motion: "prompt"           # what moves (image-to-video, vf.gen.video)
    last_image / last_keyframe # optional end frame
    seconds: 5                 # clip length (<= 5 s recommended)
    seed: 1
    upscale: 2                 # Real-ESRGAN factor before compositing (0 = off)
    fit / focus / zoom         # passed to the resulting video layer

`{name}` in prompts is replaced by series.yaml `characters.name` (reuse identical wording = consistency).
The style profile wraps every prompt (prefix/suffix) and sets the clip timing (gen_fps, step).
Everything is cached in the global tier: the same prompt+seed+model+code is never generated twice.
"""
import math, os, re
from .spec import resolve, FORMATS

PROFILE_FPS = {'fast': 24, 'fast_vae': 24, 'fastwan': 24, 'quality': 16, 'k6': 24}
K6_SKIP = 4  # frames dropped from the start of every k6 clip (start-of-clip pop)


def _wrap(spec, text, kind='keyframe', g=None):
    from .styles import wrap_prompt, shot_style
    return wrap_prompt(shot_style(spec.get('style'), g), text, (spec['series'] or {}).get('characters'), kind=kind)


def _aspect(formats, size=None):
    """Generate portrait clips when only 9:16 is requested, else landscape (9:16 crops a landscape clip).
    size = [long, short] side in px (multiples of 32; default 832x480, the fast profile's ~50 s/clip size)."""
    a, b = (size or (832, 480))
    a, b = max(a, b), min(a, b)
    return (b, a) if formats == ['short'] else (a, b)


def _apply_defaults(spec):
    from .spec import _merge
    for s in spec['shots']:
        if s.get('gen') and spec.get('gen'):
            s['gen'] = _merge(spec['gen'], s['gen'])


ANCHOR_PROMPT = ('close-up portrait of {%s}, facing the camera, neutral expression, soft frontal key light, '
                 'plain dark background, sharp focus on the face')


def _cast_path(spec, name, exists=False):
    """Series-level identity anchor for a character: series.yaml `cast: {name: path}` or <series>/cast/<name>.png.
    Recurring leads (protagonist/antagonist) keep one face across every episode; delete the file to recast."""
    sd = spec.get('series_dir')
    if not sd:
        return None
    rel = ((spec['series'] or {}).get('cast') or {}).get(name)
    if isinstance(rel, dict):  # cast sheet entry (vf/cast.py): its `anchor`, else the default path
        rel = rel.get('anchor')
    rel = rel or os.path.join('cast', f'{name}.png')
    p = rel if os.path.isabs(rel) else os.path.join(sd, rel)
    return p if (not exists or os.path.exists(p)) else None


def _kf_size(formats, g):
    # at least ~0.55 MP (Z-Image-Turbo's detail floor), else the clip size: i2v uses the clip size anyway, and
    # 1.3 MP stills hit the 8 GB VRAM limit (97 s each vs ~35 s)
    W, H = _aspect(formats, g.get('size'))
    k = max(1.0, (0.55e6 / (W * H)) ** 0.5)
    return int(W * k) // 16 * 16, int(H * k) // 16 * 16


def keyframes(spec, formats, log=print):
    """Stage 1 only: first frames for every gen shot (sets gen['_image']). Returns [(shot, path)].

    Character consistency: every character named in a keyframe (`{detective}`) gets one ANCHOR portrait (fixed seed,
    from the series sheet). Shots with a character draw `keyframe_candidates` stills (default 3; 1 when
    `keyframe_seed` pins one) and keep the face closest to the anchor (vf/identity.py). `image_from: <shot id>`
    reuses another shot's keyframe (one look for a recurring place)."""
    from .gen.bridge import run_gen
    _apply_defaults(spec)
    shots = [s for s in spec['shots'] if s.get('gen')]
    chars = (spec['series'] or {}).get('characters') or {}
    id_seed = int((spec['series'] or {}).get('identity_seed', 1))
    jobs, owners = [], []          # owners[i] = ('anchor', name) | ('cand', shot, k)
    anchors = {}
    from . import cast as castmod
    lock = castmod.enabled(spec)   # cast lock (vf/cast.py): opt-in per series/episode; off = the code below unchanged
    sheet = castmod.sheet(spec) if lock else {}
    locked = []
    for s in shots:
        g = s['gen']
        keys = castmod.shot_cast(spec, s, sheet) if lock and sheet else []
        if g.get('image'):
            g['_image'] = resolve(spec, g['image'])
            if keys and g.get('cast_refine'):
                g['_cast_keys'] = keys
                locked.append(s)
            elif keys and g.get('cast_refine') is None and (s.get('cast_gate') or g.get('cast_gate')) not in ('clip', 'final'):
                # auto: a supplied keyframe below the identity threshold gets the Klein redraw + re-roll; passing
                # ones are untouched (same cache keys). `cast_refine: false` opts a shot out.
                thr = max(sheet[k]['threshold'] for k in keys)
                tot = castmod._total(castmod.score(g['_image'], keys, sheet))
                if 0 <= tot < thr:  # -1 = no measurable face: a redraw has nothing to fix
                    log(f"    {s['id']}: keyframe identity {tot:.3f} < {thr} -> cast redraw")
                    g['_cast_keys'], g['_cast_auto'] = keys, True
                    locked.append(s)
        elif g.get('keyframe') and not g.get('image_from') and keys:
            g['_cast_keys'] = keys
            locked.append(s)
            for j in castmod.t2i_jobs(spec, s, formats):  # round-0 candidates join this batch (one encoder load)
                jobs.append(j)
                owners.append(('cast', s))
        elif g.get('keyframe') and not g.get('image_from'):
            W, H = _kf_size(formats, g)
            names = [n for n in re.findall(r'\{(\w+)\}', g['keyframe']) if n in chars]
            pinned = 'keyframe_seed' in g
            k = 1 if pinned or not names else int(g.get('keyframe_candidates', 3))
            seed0 = int(g.get('keyframe_seed', g.get('seed', 1)))
            for c in range(k):
                jobs.append(dict(prompt=_wrap(spec, g['keyframe'], g=g), width=W, height=H, seed=seed0 + c * 101))
                owners.append(('cand', s, c))
            g['_cands'], g['_chars'] = [], names
            for n in names[:1]:
                if (n, W, H) not in anchors and not _cast_path(spec, n, exists=True):
                    anchors[(n, W, H)] = len(jobs)
                    jobs.append(dict(prompt=_wrap(spec, ANCHOR_PROMPT % n), width=W, height=H, seed=id_seed))
                    owners.append(('anchor', (n, W, H)))
        if g.get('last_image'):
            g['_last'] = resolve(spec, g['last_image'])
    if jobs:
        log(f'  keyframes: {len(jobs)} stills ({len(anchors)} identity anchor(s))')
        from .gpulock import gpu_lock
        with gpu_lock('vf keyframes'):
            res = run_gen('image', jobs)
        anchor_out = {}
        for o, r in zip(owners, res):
            if o[0] == 'cast':
                o[1]['gen'].setdefault('_cast_r0', []).append(r['out'])
                continue
            if o[0] == 'anchor':
                anchor_out[o[1]] = r['out']
                p = _cast_path(spec, o[1][0])  # the series keeps it: every later episode uses the same face
                if p and not os.path.exists(p):
                    import shutil
                    os.makedirs(os.path.dirname(p), exist_ok=True)
                    shutil.copyfile(r['out'], p)
                    log(f'    cast anchor saved: {p}')
            else:
                o[1]['gen']['_cands'].append(r['out'])
        for s in shots:
            g = s['gen']
            cands = g.pop('_cands', None)
            if not cands:
                continue
            g['_image'] = cands[0]
            names = g.pop('_chars', [])
            if len(cands) > 1 and names:
                W, H = _kf_size(formats, g)
                from .identity import pick
                anchor = _cast_path(spec, names[0], exists=True) or anchor_out[(names[0], W, H)]
                best, scores = pick(anchor, cands)
                g['_image'] = cands[best]
                g['_kf_pick'] = dict(char=names[0], chosen=best, scores=[None if x is None else round(x, 3)
                                                                         for x in scores])
                log(f"    {s['id']}: identity {names[0]} -> candidate {best} {g['_kf_pick']['scores']}")
    if locked:
        log(f'  cast lock: {len(locked)} shot(s) conditioned on the cast sheet references')
        castmod.lock_keyframes(spec, locked, formats, log)
        for s in locked:
            s['gen'].pop('_cast_keys', None)
    by_id = {s['id']: s for s in shots}
    for s in shots:  # location/look reuse
        src = s['gen'].get('image_from')
        if src:
            if src not in by_id or not by_id[src]['gen'].get('_image'):
                raise ValueError(f"shot {s['id']}: image_from {src!r} is not a gen shot with a keyframe")
            s['gen']['_image'] = by_id[src]['gen']['_image']
    if lock and sheet:
        try:
            castmod.report(spec, log, clips=False)
        except Exception as e:  # a report must never stop the stage
            log(f'  cast QC skipped: {type(e).__name__}: {e}')
    return [(s, s['gen'].get('_image')) for s in shots]


def contact_sheet(items, out, cols=6, w=270):
    """Grid of (label, image path) thumbnails for review."""
    import cv2, numpy as np
    thumbs = []
    for label, p in items:
        im = cv2.imread(p) if p else None
        if im is None:
            im = np.zeros((480, 270, 3), np.uint8)
        im = cv2.resize(im, (w, int(im.shape[0] * w / im.shape[1])), interpolation=cv2.INTER_AREA)
        cv2.rectangle(im, (0, 0), (w, 26), (0, 0, 0), -1)
        cv2.putText(im, label, (6, 19), cv2.FONT_HERSHEY_SIMPLEX, 0.55, (255, 255, 255), 1, cv2.LINE_AA)
        thumbs.append(im)
    h = max(t.shape[0] for t in thumbs)
    thumbs = [np.pad(t, ((0, h - t.shape[0]), (0, 0), (0, 0))) for t in thumbs]
    while len(thumbs) % cols:
        thumbs.append(np.zeros_like(thumbs[0]))
    rows = [np.hstack(thumbs[i:i + cols]) for i in range(0, len(thumbs), cols)]
    cv2.imwrite(out, np.vstack(rows))
    return out


MAX_CLIP_S = 5.0     # Wan TI2V-5B: 121 frames @ 24 fps
TAIL_S = 0.5         # extra clip time generated so QC can pick the cleanest window


_HINT_WORDS = dict(
    people=r"\b(he|she|his|her|man|woman|person|detective|figure|face|hand|eyes|{)",
    smoke=r"\b(smoke|steam|fog|mist|haze|breath)\b",
    water=r"\b(rain|water|puddle|sea|harbor|harbour|river|wet|waves?)\b",
)


def qc_hints(spec, s):
    """What the clip QC should expect, from the prompts (overridable with `gen: {qc: {...}}`)."""
    g = s['gen']
    text = ' '.join(str(g.get(k, '')) for k in ('keyframe', 'motion')).lower()
    h = dict(locked=True, people=bool(re.search(_HINT_WORDS['people'], text)),
             smoke=bool(re.search(_HINT_WORDS['smoke'], text)), water=bool(re.search(_HINT_WORDS['water'], text)),
             faces_speaking=bool(g.get('lip_sync')))
    if (g.get('profile') or (spec.get('gen') or {}).get('profile')) == 'k6':
        h['skip_start'] = K6_SKIP  # these frames are cut from the edit, so QC must not re-roll for them
    h.update(g.get('qc') or {})
    return h


def _clip_frames(s, fps):
    """Frames to generate: the shot's clip-time span (dur x speed) + a QC tail, capped at the model's 5 s."""
    g = s['gen']
    need = float(g.get('seconds', s['dur'] * float(g.get('speed', 1.0))))
    n = int(round(min(MAX_CLIP_S, need + TAIL_S) * fps))
    return max(5, n - (n - 1) % 4)  # Wan needs 4k+1 frames


def _video_jobs(spec, shots, formats):
    jobs = []
    for s in shots:
        g = s['gen']
        if not g.get('_image'):
            raise ValueError(f"shot {s['id']}: gen needs `image:` or `keyframe:`")
        prof = g.get('profile') or (spec.get('models') or {}).get('video_profile') or \
            ('quality' if g.get('_last') else 'fast')
        fps = PROFILE_FPS.get(prof, 24)
        if prof == 'k6':  # vf/k6.py: 384x672, or 480x864 for face close-ups (gen: {hires: true})
            from .k6 import SIZE
            w, h = SIZE[bool(g.get('hires'))]
            if g.get('k6_size'):  # explicit portrait [W, H] (multiples of 32), e.g. [576, 1024] for a short clip
                w, h = (int(x) for x in g['k6_size'])
            if g.get('engine') == 'wan':  # Wan 2.2 TI2V 5B through the k6 path (same QC, trim, lip-sync, finish)
                from .k6 import WAN_SIZE
                w, h = WAN_SIZE
            W, H = (w, h) if formats == ['short'] else (h, w)
        else:
            W, H = _aspect(formats, g.get('size'))
        job = dict(image=os.path.abspath(g['_image']),
                   # motion prompts follow the EPISODE style; `motion_style` (opt-in) overrides it per shot, e.g. a
                   # trailer reusing another episode's shots must wrap them in that episode's style (same cache key)
                   prompt=_wrap(spec, g.get('motion', g.get('keyframe', '')), kind='motion',
                                **({'g': {'style': g['motion_style']}} if g.get('motion_style') else {})),
                   seed=int(g.get('seed', 1)), frames=_clip_frames(s, fps), width=W, height=H, profile=prof)
        if g.get('steps'):
            job['steps'] = int(g['steps'])
        if prof == 'k6' and g.get('engine') == 'wan':
            job['engine'] = 'wan'
        if g.get('_last'):  # only pass what's set: the cache keys on the arguments actually given
            job['last_image'] = os.path.abspath(g['_last'])
        jobs.append(job)
    return jobs


def _qc_clip(path, hints):
    """(clip path, report): analyse; when it fails, try the cheap repair (smear patch / stabilise, ~2 s) and keep
    the repaired clip if it is better. A re-roll (~50 s) is only spent when the repair can't fix it."""
    from . import clipqc
    rep = clipqc.analyze(path, hints)
    if rep.get('fail') or rep.get('transient', {}).get('events'):
        fixed = clipqc.repair(path, rep, hints)
        if fixed != path:
            rep2 = clipqc.analyze(fixed, hints)
            if rep2.get('score', 99) <= rep.get('score', 99):
                return fixed, rep2
    return path, rep


def _judge_jobs(spec, shots_clips):
    """Vision-judge jobs (vf/gen/judge.py, Qwen3-VL-4B): the generic 'appear' check (things popping in/out: hands,
    people, props) + 'text' (no AI lettering), plus the shot's own `gen: {judge: [{q, expect}]}` questions written
    from its intent. `judge: false` skips; `qc: {appear: false}` for shots meant to bring someone in."""
    jobs = []
    for s, clip in shots_clips:
        g = s['gen']
        if g.get('judge') is False:
            jobs.append(None)
            continue
        qc = g.get('qc') or {}  # `qc: {text: false}` for shots whose lettering is intended (an embossed badge number)
        cl = ([] if qc.get('text') is False else ['text']) + ([] if qc.get('appear') is False else ['appear'])
        qs = list(g.get('judge') or []) + _persist_questions(g) + _silent_mouth_questions(spec, s)
        jobs.append(dict(clip=os.path.abspath(clip), questions=qs, checklist=cl, frames=12, describe=False))
    return jobs


# Props the story depends on: if the motion prompt names one, the clip must keep it in every frame. The judge
# answers "is X visible in every frame" reliably (it is an appear/vanish question), unlike generic glitch checks.
# (2026-11-02: the cigarette vanished into the exhale and nothing flagged it.)
PROPS = ('cigarette', 'receiver', 'telephone', 'phone booth', 'payphone', 'coat', 'hat', 'badge', 'logbook',
         'case file', 'photograph', 'ashtray', 'flashlight', 'cord', 'umbrella', 'gun')  # not light words (lamp/bulb)


_PERSON = r'\b(man|woman|detective|he|she|his|her|face|person|girl|boy)\b'


def _silent_mouth_questions(spec, s):
    """A face on screen while a voice-over line plays (no lip-sync): any mouth movement reads as badly synced
    speech (user, 2026-11-02: "the lips overlap on the voice over"). The judge must see the lips stay sealed."""
    g = s['gen']
    if (g.get('lipsync') or g.get('lip_sync') or g.get('mouth_check') is False
            or not re.search(_PERSON, str(g.get('motion', '')).lower())):
        return []
    from .captions import line_timings
    t0, t1 = s['start'], s['start'] + s['dur']
    if not any(a < t1 and b > t0 for a, b, _, _ in line_timings(spec)):
        return []
    return [dict(q="Does anyone's mouth open, or do their lips part or move as if talking, in any of these frames?",
                 expect='no')]


def _persist_questions(g):
    if g.get('persist') is False:
        return []
    mot = str(g.get('motion', '')).lower()
    names = list(g.get('persist') or []) or [p for p in PROPS if re.search(rf'\b{p}s?\b', mot)]
    return [dict(q=f'Is the {p} clearly visible in every one of these frames, from the first to the last, without '
                   f'disappearing, vanishing into smoke or changing into something else?', expect='yes')
            for p in names[:4]]


def _run_judge(bridge, spec, shots_clips, log):
    """[(fail, reasons)] per (shot, clip); never blocks a build if the judge can't run."""
    jobs = _judge_jobs(spec, shots_clips)
    todo = [j for j in jobs if j]
    out = [(False, [])] * len(jobs)
    if not todo or not (spec.get('gen') or {}).get('judge', True):
        return out
    try:
        from .gpulock import gpu_lock
        with gpu_lock('vf judge'):
            res = iter(bridge.run_gen('judge', todo, check=False))
        out = []
        for j in jobs:
            if not j:
                out.append((False, []))
                continue
            r = next(res)
            bad = [f"{a['q']} -> {a['answer']} (wanted {a['expect']})" for a in r.get('answers', []) if not a.get('pass')]
            out.append((bool(r.get('fail')), bad))
    except Exception as e:
        log(f'  judge skipped: {type(e).__name__}: {e}')
    return out


def generate(spec, formats, log=print, retries=None):
    """Fill every shot's gen block: keyframe -> clip -> QC (re-roll failing seeds, keep the best take) -> repair ->
    cleanest window -> 60 fps retime -> depth. Returns the number of shots that needed AI work."""
    shots = [s for s in spec['shots'] if s.get('gen')]
    if not shots:
        return 0
    from .gen import bridge
    motion = spec.get('motion') or {}
    keyframes(spec, formats, log)
    # `gen: {talk: ...}` (vf/talk.py): InfiniteTalk acts the line; runs first because it moves shot boundaries, and
    # the K6 jobs below are sized from the final durations
    from . import talk as talkmod
    talked = talkmod.stage(spec, shots, formats, log)
    shots = [s for s in shots if s not in talked]
    if not shots:
        _cast_report(spec, log)
        return len(talked)
    # `gen: {still: true}`: no AI motion at all - the keyframe is moved by the virtual camera (+ depth parallax,
    # + compositor rain/particles). For subjects that should be motionless anyway: video models invent people,
    # hands and gaits in them (judge-confirmed), a camera move over a 2.5D still cannot.
    stills = [s for s in shots if s['gen'].get('still')]
    shots = [s for s in shots if not s['gen'].get('still')]
    depth_jobs = []
    for s in stills:
        g = s['gen']
        layer = dict(type='image', src=g['_image'], fit=g.get('fit', 'cover'), sharpen=float(g.get('sharpen', 0.25)))
        for k in ('focus', 'zoom', 'tint', 'tint_amount'):
            if k in g:
                layer[k] = g[k]
        s.setdefault('layers', []).insert(0, layer)
        depth_jobs.append((layer, dict(image=os.path.abspath(g['_image']))))
        g['_take'] = dict(still=True, image=g['_image'])
    if not shots:
        _depth_pass(bridge, depth_jobs, log)
        _cast_report(spec, log)
        return len(stills) + len(talked)
    retries = int((spec.get('gen') or {}).get('retries', 2) if retries is None else retries)
    jobs = _video_jobs(spec, shots, formats)
    log(f'  clips: {len(jobs)} (QC re-rolls up to {retries} per shot)')
    best = [None] * len(shots)
    pending = list(range(len(shots)))
    # (2026-11-03 audit) no speculative finishing any more: it finished EVERY take, QC rejects included (135 MB of
    # k6fin junk each), from the raw clip at the planned speed (so the final finish of the repaired clip missed it
    # anyway), and ran on the GPU next to the judge and the next K6 batch. Only the chosen take is finished below.
    from . import cast as castmod
    cast_on = castmod.enabled(spec) and bool(castmod.sheet(spec))
    # cast gate (vf/cast.py): a clip whose face drifts below the identity threshold re-rolls even when QC re-rolls
    # are off for the shot (`retries: 0` protects approved takes from QC false positives, not from a wrong face)
    cast_rr = lambda s: int((s.get('gen') or {}).get('cast_rerolls', 1)) if cast_on else 0
    try:
        # a shot's own gen.retries counts too (it was capped by the episode-wide value, 2026-11-08)
        for attempt in range(max([retries] + [cast_rr(s) for s in shots]
                                 + [int((s.get('gen') or {}).get('retries', retries)) for s in shots]) + 1):
            batch = []
            for i in pending:
                j = dict(jobs[i])
                j['seed'] = jobs[i]['seed'] + attempt * 1000  # a far-away seed: neighbours share failure modes
                batch.append(j)
            if all(j.get('profile') == 'k6' for j in batch):  # Kandinsky 6 (vf/k6.py), separate process
                from . import k6
                if attempt:  # the QC judge (shared worker) still holds its VLM on the GPU: park it before K6 loads
                    getattr(bridge, 'park_gen', bridge.stop_gen)()  # (P41: 488 MB spill at the re-roll batch load)
                res = [dict(out=p, fps=f) for p, f in k6.clips(batch, log)]
            else:
                from .gpulock import gpu_lock
                with gpu_lock('vf clips'):
                    res = bridge.run_gen('video', batch)
            nxt = []
            checked = [(i, r) + _qc_clip(r['out'], qc_hints(spec, shots[i])) for i, r in zip(pending, res)]
            verdicts = _run_judge(bridge, spec, [(shots[i], clip) for i, _, clip, _ in checked], log)
            for (i, r, clip, rep), (jfail, jwhy) in zip(checked, verdicts):
                s = shots[i]
                if jfail:  # semantic error (prop teleports, someone pops in): worse than any pixel defect
                    rep = dict(rep, fail=True, score=rep.get('score', 0) + 5.0,
                               reasons=list(rep.get('reasons', [])) + ['judge: ' + '; '.join(jwhy)])
                cmed, cthr = castmod.clip_gate(spec, s, clip) if cast_on else (None, None)
                # the gate sees the RAW clip, the report (and the viewer) the finished one: finishing moved identity
                # by -0.04..+0.01 (Q7: raw .600 passed, finished .558 flagged). Demand a margin on the raw clip.
                cmargin = float((s.get('gen') or {}).get('cast_clip_margin',
                                (spec.get('series') or {}).get('cast_clip_margin', 0.04)))
                cfail = cmed is not None and cmed < cthr + cmargin
                if cmed is not None:
                    rep = dict(rep, cast=cmed, score=rep.get('score', 0) + (5.0 + 10 * (cthr + cmargin - cmed) if cfail else 0))
                    if cfail:
                        rep['reasons'] = list(rep.get('reasons', [])) + [f'cast identity {cmed} < {cthr} + {cmargin}']
                take = dict(out=clip, raw=r['out'], fps=int(r.get('fps', 24)), qc=rep,
                            seed=batch[pending.index(i)]['seed'])
                if best[i] is None or rep.get('score', 0) < best[i]['qc'].get('score', 0):
                    best[i] = take
                swing = ((s.get('gen') or {}).get('lock') or {}).get('mode') == 'swing'
                if cfail and attempt < cast_rr(s):
                    nxt.append(i)
                    log(f"    {s['id']}: cast identity {cmed} < {cthr} + margin {cmargin} (raw clip) -> re-roll")
                elif cfail:
                    log(f"    {s['id']}: FLAG cast identity still below {cthr} after {cast_rr(s)} re-roll(s); kept the "
                        f"best take (identity {best[i]['qc'].get('cast')})")
                elif rep.get('fail') and swing:  # swing shots use one plate frame, not the AI motion: no re-roll
                    log(f"    {s['id']}: QC fail ignored (lock mode swing uses only the plate frame)")
                elif rep.get('fail') and attempt < int((s.get('gen') or {}).get('retries', retries)):  # gen retries: 0 = take approved by the user
                    nxt.append(i)
                    log(f"    {s['id']}: QC fail ({'; '.join(rep.get('reasons', []))}) -> re-roll")
                elif rep.get('fail'):
                    log(f"    {s['id']}: QC still failing after {int((s.get('gen') or {}).get('retries', retries))} re-rolls; kept the best take "
                        f"(score {best[i]['qc'].get('score')}) - consider restaging the shot")
            pending = nxt
            if not pending:
                break
    finally:
        # the model worker holds 5-7 GB of VRAM: hand it back before the GPU renders (park keeps it in RAM)
        getattr(bridge, 'park_gen', bridge.stop_gen)()
    for i, s in enumerate(shots):
        g, b = s['gen'], best[i]
        clip, fps = b['out'], b['fps']
        g['_take'] = dict(seed=b['seed'], clip=clip, raw=b['raw'], score=b['qc'].get('score'),
                          fail=b['qc'].get('fail'), reasons=b['qc'].get('reasons'), notes=b['qc'].get('notes'))
        from . import clipqc
        need = int(math.ceil(s['dur'] * float(g.get('speed', 1.0)) * fps)) + 1
        a = clipqc.best_window(b['qc'], need)[0] if b['qc'].get('frames', 0) > need else 0
        if jobs[i].get('profile') == 'k6' and b['qc'].get('frames', 0) - K6_SKIP >= need:
            a = max(a, K6_SKIP)  # Kandinsky's first ~4 frames "pop" (measured 2026-11-02: transient 79 vs 14 median)
        n_clip = b['qc'].get('frames') or 0
        span = (n_clip - a if n_clip else 0) / fps
        sp = float(g.get('speed', 1.0))
        if span and s['dur'] * sp > span + 1e-3:  # would run past the clip end and freeze: slow it down instead
            sp_new = max(0.6, span / s['dur'])
            log(f"    {s['id']}: clip covers {span:.2f}s of a {s['dur']:.2f}s shot -> speed {sp:.2f} -> {sp_new:.2f}")
            g['speed'] = sp = sp_new
        if jobs[i].get('profile') == 'k6':  # lip-sync -> denoise -> exposure -> NVIDIA frame gen -> 4x RTX VSR
            from . import k6
            from .interp import target_fps
            ft = round(target_fps(spec.get('fps', 60), sp), 4)
            ls = None
            if g.get('lipsync'):  # {line: <text prefix>, engine, mask}: the voice take placed at its shot offset
                l = g['lipsync']
                d = next(x for x in spec['dialogue'] if x['text'].startswith(l['line']))
                ls = dict(engine=l.get('engine', 'musetalk'), mask=l.get('mask', ''), wav=d['_wav'],
                          # clip time of the line = window start + shot time x speed (the clip plays at `speed`).
                          # Was `at - start - a/fps`: wrong sign, no speed; harmless only while a == 0 and speed ~1
                          # (Q5 2026-11-03: a = 4, speed .66 -> offset -0.067 crashed MuseTalk).
                          offset=round(a / fps + (float(d['at']) - s['start']) * sp, 3),
                          **({'rate': round(sp, 4)} if abs(sp - 1) > 1e-3 else {}),
                          **{k: l[k] for k in ('late', 'rev') if l.get(k)})  # late: after framegen + upscale; rev: code revision (cache key)
            fin = k6.finish(clip, fps, ft, lipsync=ls, log=log, **_k6_finish_opts(spec, s, formats))
            if g.get('lock'):  # freeze all but one region (the model sways the whole set): vf/platelock.py
                from .platelock import lock
                fin = lock(fin, start=a / fps, **g['lock'])
            if g.get('erase'):  # paint a stray static object out of a blurred background: vf/platelock.py
                from .platelock import erase
                fin = erase(fin, start=a / fps, **g['erase'])
            if g.get('face_tone'):  # match a face's tone/lip colour to a neighbour shot of the same character
                from .facetone import face_tone
                fin = face_tone(fin, **g['face_tone'])
            stamps = list(g['stamp'] if isinstance(g.get('stamp'), list) else ([g['stamp']] if g.get('stamp') else []))
            if g.get('ink'):  # text written into a prop on the keyframe, carried onto the clip as ink: vf/inktext.py
                from .inktext import stamp_entry
                stamps.append(stamp_entry(g['_image'], g['ink']))
            if stamps:  # keyframe edit warped onto the clip, clip's own light: vf/platelock.py
                from .platelock import stamp
                for st in stamps:  # several edits in order
                    fin = stamp(fin, start=a / fps, **st)
            if g.get('retex'):  # carry a keyframe edit (stamped lettering) onto the finished clip: vf/platelock.py
                from .platelock import retex
                fin = retex(fin, start=a / fps, **g['retex'])
            layer = dict(type='video', src=fin, fps=ft, fit=g.get('fit', 'cover'), start=a / fps, speed=sp,
                         sharpen=float(g.get('sharpen', 0.0)))
            for k in ('focus', 'zoom', 'tint', 'tint_amount'):
                if k in g:
                    layer[k] = g[k]
            s.setdefault('layers', []).insert(0, layer)
            continue
        if g.get('lock'):  # 2026-11-10: plate lock for the Wan path too (was K6 only); owner: "too shaky"
            from .platelock import lock
            clip = lock(clip, start=a / fps, **g['lock'])
        up = int(g.get('upscale', 0))  # the only fast upscaler is anime-tuned: opt in per style/series (anime: 2)
        if up > 1:
            from .upscale import upscale_clip
            clip = upscale_clip(clip, up, fps=fps)
        layer = dict(type='video', src=clip, fps=fps, step=int(motion.get('step', 1)), fit=g.get('fit', 'cover'),
                     start=a / fps, speed=sp, sharpen=float(g.get('sharpen', 0.0 if up > 1 else 0.35)))
        if motion.get('interpolate', True) and int(motion.get('step', 1)) <= 1:
            from .interp import retime, target_fps
            ft = target_fps(spec.get('fps', 60), sp)
            layer.update(src=retime(clip, fps, round(ft, 4)), fps=round(ft, 4))  # lands on the 60 fps grid
        for k in ('focus', 'zoom', 'tint', 'tint_amount'):
            if k in g:
                layer[k] = g[k]
        for fmt in FORMATS:
            if fmt in g:
                layer[fmt] = g[fmt]
        s.setdefault('layers', []).insert(0, layer)
        cam = __import__('vf.camera', fromlist=['settings']).settings(spec, s)
        if cam and float(cam.get('parallax', 0)) > 0 and g.get('_image'):
            depth_jobs.append((layer, dict(image=os.path.abspath(g['_image']))))
    _depth_pass(bridge, depth_jobs, log)
    _cast_report(spec, log)
    return len(shots) + len(stills) + len(talked)


def _cast_report(spec, log):
    """out/cast_qc.json with the finished clips (cast-locked episodes only; vf/cast.py)."""
    from . import cast as castmod
    if castmod.enabled(spec) and castmod.sheet(spec):
        try:
            castmod.report(spec, log)
        except Exception as e:
            log(f'  cast QC skipped: {type(e).__name__}: {e}')


def _k6_finish_opts(spec, s, formats):
    g = s['gen']
    grade = spec.get('grade')  # episode/series {ref: image, strength}: shot matching to one palette
    grade = dict(grade, ref=resolve(spec, grade['ref'])) if grade and g.get('grade') is not False else None
    return dict(portrait=formats == ['short'], expo=g.get('expo', 0.36), grade=grade)


def _depth_pass(bridge, depth_jobs, log):
    if not depth_jobs:
        return
    try:
        from .gpulock import gpu_lock
        with gpu_lock('vf depth'):
            res = bridge.run_gen('depth', [j for _, j in depth_jobs])
        for (layer, _), r in zip(depth_jobs, res):
            layer['depth'] = (r.get('paths') or [None])[0]
    except Exception as e:  # parallax is an enhancement: never block a build on it
        log(f'  depth skipped: {type(e).__name__}: {e}')
    finally:
        getattr(bridge, 'park_gen', bridge.stop_gen)()
